#!/usr/bin/env python3
"""Post-process a finished Normaliz ray list for the tangent cone of Q_n at the cut ray δ(S) (|S| = s):
parallel orbit reduction under G = Stab_{S_n}(δ(S)), exact consistency check, then each orbit representative
followed to its neighbour in Q_n, exactly checked to be a vertex, S_n-canonicalised and compared with the candidate
ray orbits (results/phase10/met_ray_orbits_n{n}.json).

Consistency check: for every G-orbit key, the number of rays in the file with that key must equal the orbit size
|G| / |Stab_G(ray)| computed independently by bliss; hence the sum of orbit sizes equals the file's ray count.
This also certifies the canonical form on this data (a too-fine key would undercount, a too-coarse one overcount).

Usage: python -u scripts/phase10/nmz_rays_post.py --n 8 --s 4 --file checkpoints/phase10/nmz/n8_S4.out --workers 18
Writes the |S| entry into results/phase10/nmz_cut_rays_n{n}.json.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import time
from collections import Counter
from multiprocessing import get_context
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from metricpoly import adjdec  # noqa: E402
from metricpoly.conecut import normalise_sum, perm_key, q_polytope  # noqa: E402
from metricpoly.core import pairs  # noqa: E402
from metricpoly.jobs import atomic_write_json  # noqa: E402

_G = {}


def _init(n, s):
    Q = q_polytope(n)
    D, x = normalise_sum(n, 1, [1 if (i < s) != (j < s) else 0 for i, j in pairs(n)])
    T = Q.tight(D, x)
    _G.update(n=n, Q=Q, D=D, x=x, a=Q.A[T].sum(axis=0), F=[tuple(int(v) for v in x)])


def _chunk(lines):
    n, a, F = _G["n"], _G["a"], _G["F"]
    cnt, rep = Counter(), {}
    for ln in lines:
        r = tuple(int(v) for v in ln.split())
        s = -sum(int(ai) * ri for ai, ri in zip(a, r))
        if s <= 0:
            raise RuntimeError("ray not strictly negative on the section functional")
        g = math.gcd(s, *r)
        p = (s // g, tuple(v // g for v in r))
        k = adjdec.fix_key(n, F, p)
        cnt[k] += 1
        if k not in rep:
            rep[k] = p
    return cnt, rep


def _orbit(item):
    k, p = item
    return k, adjdec.orbit_size(_G["n"], _G["F"], p)


def _neighbour(item):
    k, p = item
    n, Q, D, x = _G["n"], _G["Q"], _G["D"], _G["x"]
    y = adjdec.HPoly(Q.A, Q.b).step(D, x, p[1])
    if not Q.is_vertex(*y):
        return k, None
    return k, perm_key(n, *normalise_sum(n, *y))


def read_rays(path, section="extreme rays"):
    with open(path, encoding="ascii") as fh:
        for ln in fh:
            if ln.strip().endswith(section + ":") and ln.split()[0].isdigit():
                k = int(ln.split()[0])
                break
        else:
            raise RuntimeError(f"no {section} section")
        buf = []
        for _ in range(k):
            buf.append(fh.readline())
            if len(buf) == 20000:
                yield buf
                buf = []
        if buf:
            yield buf
    read_rays.total = k


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=8)
    ap.add_argument("--s", type=int, required=True)
    ap.add_argument("--file", required=True)
    ap.add_argument("--workers", type=int, default=18)
    ap.add_argument("--dual", action="store_true",
                    help="file is from dual input (cone generated by the rows of -A_T, SupportHyperplanes): "
                         "our rays are its support hyperplanes")
    a = ap.parse_args()
    n, s = a.n, a.s
    t0 = time.time()
    cnt, rep = Counter(), {}
    with get_context("spawn").Pool(a.workers, initializer=_init, initargs=(n, s)) as pool:
        for i, (c, r) in enumerate(pool.imap_unordered(_chunk, read_rays(ROOT / a.file, "support hyperplanes" if a.dual else "extreme rays"))):
            cnt.update(c)
            for k, p in r.items():
                rep.setdefault(k, p)
            if i % 25 == 0:
                print(f"  chunks {i + 1}, rays {sum(cnt.values())}, orbits {len(cnt)}, {time.time() - t0:.0f} s",
                      flush=True)
        total = sum(cnt.values())
        sizes = dict(pool.map(_orbit, list(rep.items())))
        mismatch = [k for k in cnt if cnt[k] != sizes[k]]
        print(f"rays {total}, orbits {len(cnt)}, count/orbit-size mismatches {len(mismatch)}, "
              f"{time.time() - t0:.0f} s", flush=True)
        nb = dict(pool.map(_neighbour, list(rep.items())))
    nonv = sum(1 for v in nb.values() if v is None)
    keys = {v for v in nb.values() if v is not None}
    cand = set(json.loads((ROOT / "results" / "phase10" / f"met_ray_orbits_n{n}.json").read_text()))
    outside = sorted(k for k in keys if k not in cand)
    outp = ROOT / "results" / "phase10" / f"nmz_cut_rays_n{n}.json"
    out = json.loads(outp.read_text()) if outp.exists() else {}
    _init(n, s)
    Q, D, x = _G["Q"], _G["D"], _G["x"]
    out[str(s)] = {"tight": int(len(Q.tight(D, x))), "cone_rays": total, "ray_orbits_under_stabiliser": len(cnt),
                   "stabiliser_order": adjdec.group_order(n, _G["F"]), "count_vs_orbit_size_mismatches": len(mismatch),
                   "neighbour_orbits": len(keys), "nonvertex": nonv, "outside_candidates": outside,
                   "postprocess_s": round(time.time() - t0, 1), "source": a.file,
                   "normaliz_input": ("dual: cone of the rows of -A_T, SupportHyperplanes" if a.dual
                                      else "inequalities (primal), ExtremeRays")}
    atomic_write_json(outp, out)
    print(f"[n={n} |S|={s}] rays {total}, orbits {len(cnt)}, mismatches {len(mismatch)}, neighbour orbits "
          f"{len(keys)}, nonvertex {nonv}, outside candidates {len(outside)}", flush=True)


if __name__ == "__main__":
    main()
