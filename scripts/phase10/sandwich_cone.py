#!/usr/bin/env python3
"""E1/E2 gate for the "sandwich" attack on CUT_n facet completeness.

R(H*) = the polytope cut out by the facet classes H* of CUT_n (SMAPO list) whose number of roots (tight cuts) exceeds
--min-roots; the triangle class is always included, so CUT_n ⊆ R ⊆ m_n. The plan needs all vertices of R; its
hardest vertex is expected to be the zero cut. This script computes the tangent cone of R at the zero cut,
    K = {d : a·d <= 0 for every member a·x <= 0 of H* through the zero cut}
(the triangle members through 0 are exactly the rows of MET_n), and reports its extreme-ray count and S_n-orbits.
Reference points: MET_n (H* = triangles only; 119,269,588 rays at n = 8) and the cut cone (all classes; 2^(n-1) - 1
rays). Every cut ray must appear among K's rays (cuts are vertices of R, adjacent to 0 in CUT_n ⊆ R... checked).

Members through 0: for a class representative a·x <= b and each root δ(S), the switching by S gives a2·x <= 0;
its S_n-orbit is enumerated exactly (all n! permutations, vectorised) and deduplicated.
Normaliz (dual input: cone generated by the rows; its support hyperplanes are K's rays), with the resguard memory
cap (default 40 GB) and the time budget below. Exact orbit counting by bliss (adjdec.fix_key with F = []).

Usage: python -u scripts/phase10/sandwich_cone.py --n 8 --min-roots 60 --budget 1200 --threads 18
Appends to results/phase10/sandwich_cone_n{n}.json.
"""
from __future__ import annotations

import argparse
import gzip
import itertools
import json
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts" / "phase10"))

from metricpoly import adjdec, resguard  # noqa: E402
from metricpoly.core import pairs  # noqa: E402
from metricpoly.jobs import atomic_write_json  # noqa: E402


def classes(n):
    if n == 9:
        import cap_lemma_lp9 as c9
        return c9.read_classes()
    import cap_lemma_lp as cl
    return cl.parse_classes(n)


def perm_pair_index(n):
    pr = pairs(n)
    idx = {e: t for t, e in enumerate(pr)}
    P = []
    for p in itertools.permutations(range(n)):
        P.append([idx[(min(p[i], p[j]), max(p[i], p[j]))] for i, j in pr])
    return np.array(P, dtype=np.int16)


def members_at_zero(n, a, b, PI):
    import cap_lemma_lp as cl
    pr = pairs(n)
    av = np.array(a, dtype=np.int64)
    reps = set()
    for S, c in cl.cuts(n):
        if int(av @ c) == b:
            a2, b2 = cl.switch(a, b, S, pr)
            assert b2 == 0
            reps.add(tuple(a2))
    out = set()
    for r in reps:
        rv = np.array(r, dtype=np.int64)
        imgs = np.empty((len(PI), len(r)), dtype=np.int64)
        np.put_along_axis(imgs, PI.astype(np.int64), np.broadcast_to(rv, imgs.shape), axis=1)  # imgs[t, p_t(e)] = r[e]
        out.update(map(tuple, np.unique(imgs, axis=0).tolist()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--min-roots", type=int, required=True, help="H* = classes with more roots than this, + triangle")
    ap.add_argument("--budget", type=float, default=1200)
    ap.add_argument("--threads", type=int, default=18)
    a = ap.parse_args()
    n = a.n
    t0 = time.time()
    resguard.require_disk()
    import cap_lemma_lp as cl
    pr = pairs(n)
    C = classes(n)
    PI = perm_pair_index(n)
    rows, picked = set(), []
    for k, (av, b) in enumerate(C):
        ntight = sum(1 for S, c in cl.cuts(n) if int(np.array(av) @ c) == b)
        tri = sorted(av) == sorted([1, -1, -1] + [0] * (len(pr) - 3)) or sorted(av) == sorted([-1, 1, 1] + [0] * (len(pr) - 3))
        if ntight > a.min_roots or tri:
            m = members_at_zero(n, av, b, PI)
            picked.append({"class": k + 1, "roots": ntight, "members_at_zero": len(m)})
            rows |= m
    AT = np.array(sorted(rows), dtype=np.int64)
    print(f"[n={n} roots>{a.min_roots}] {len(picked)} classes, {len(AT)} inequalities at the zero cut "
          f"({time.time() - t0:.0f} s)", flush=True)
    ctx = adjdec.Ctx(threads=a.threads, tag=f"sw{n}_{a.min_roots}")
    rec = {"min_roots": a.min_roots, "classes": picked, "inequalities": len(AT)}
    try:
        rays = adjdec._nmz_run(AT, ctx.tag, a.threads, a.budget, ctx)
        rec["status"] = "done"
    except adjdec.NmzTimeout:
        rays = None
        rec["status"] = ("memory cap" if ctx.stats.calls.get("nmz_memcap") else "time budget") + " exceeded"
    rec["normaliz_s"] = round(time.time() - t0, 1)
    if rays is not None:
        cutrays = {tuple(1 if (i in S) != (j in S) else 0 for i, j in pr) for S, _ in cl.cuts(n) if S}
        rs = {tuple(r) for r in rays}
        orb = Counter(adjdec.fix_key(n, [], (1, r)) for r in rs)
        rec.update(rays=len(rays), orbits=len(orb), all_cut_rays_present=cutrays <= rs,
                   valid=bool((AT @ np.array(sorted(rs), dtype=np.int64).T <= 0).all()))
    rec["seconds"] = round(time.time() - t0, 1)
    outp = ROOT / "results" / "phase10" / f"sandwich_cone_n{n}.json"
    out = json.loads(outp.read_text()) if outp.exists() else {}
    out[str(a.min_roots)] = rec
    atomic_write_json(outp, out)
    print(json.dumps({k: v for k, v in rec.items() if k != "classes"}), flush=True)


if __name__ == "__main__":
    main()
