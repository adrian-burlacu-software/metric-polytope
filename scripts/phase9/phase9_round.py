from common import ACCEPTED, ROOT, eval_structural_on, interpreter, load_json, point_from_json, verify_vertex  # noqa: E402
from judge import CK, OUT, load_base, make_is_base, summarize, targets  # noqa: E402

from metricpoly import deza, group  # noqa: E402
from metricpoly.jobs import atomic_write_json, atomic_write_text, code_version, git_head  # noqa: E402
from metricpoly.reach import Engine  # noqa: E402

PY = sys.executable
DRY = {"on": False}


_FW = {}


def _fw_init(files, invs):
    I, _ = interpreter(files)
    _FW["I"] = I
    _FW["inv"] = invs


def _fw_apply(args):
    """Outputs of the move on the whole orbit of x that are (up to symmetry) unreached nodes. Filter by the exact
    orbit invariant first; equality is then decided by the canonical form."""
    from metricpoly import core as _core
    from metricpoly.reach import orbit_invariant
    name, x = args
    I = _FW["I"]
    try:
        outs = I.apply_move(I.moves[name], [x], as_orbits=True)
    except Exception:
        return []
    seen, keys = set(), set()
    for o in outs:
        if o.n > 9 or (o.n, o.D, o.nums) in seen:
            continue
        seen.add((o.n, o.D, o.nums))
        if orbit_invariant(o) in _FW["inv"] and _core.is_feasible(o):
            keys.add(group.canonical(o).key())
    return sorted(keys)


class Forward:
    """Pool of interpreters (rule set + given files) applying user moves forward to node representatives."""

    def __init__(self, eng, files, workers, unreached_keys):
        self.eng, self.files, self.workers = eng, [str(f) for f in files], workers
        self.invs = set(eng.invariants(list(unreached_keys)).values())

    def __enter__(self):
        import multiprocessing as mp
        self.pool = mp.Pool(self.workers, initializer=_fw_init, initargs=(self.files, self.invs))
        return self

    def __exit__(self, *a):
        self.pool.terminate()

    def __call__(self, name, keys):
        res = self.pool.map(_fw_apply, [(name, self.eng.point(k)) for k in keys], chunksize=4)
        return dict(zip(keys, res))


def load_state():
    reached = {k: tuple(v) for k, v in load_json(CK / "reached.json").items()}
    st = load_json(CK / "state.json") if (CK / "state.json").exists() else {"extra_base": [], "moves": {}, "history": []}
    return reached, st


def write_state(eng, T, reached, st):
    atomic_write_json(CK / "reached.json", {k: list(v) for k, v in reached.items()})
    atomic_write_json(CK / "state.json", st)
    unr_t = [i for i in range(len(T)) if eng.target_key(i) not in reached]
    atomic_write_json(OUT / "unreached_nodes.json", {
        "note": "keys = canonical keys 'n|D|nums' of every unreached node (restrictions of targets); target_keys = "
                "unreached targets (whole orbits). Generated by the judge; read-only for agents.",
        "keys": sorted(k for k in eng.rep if k not in reached),
        "target_keys": sorted({eng.target_key(i) for i in unr_t})})
    atomic_write_json(OUT / "unreached_targets.json", [
        {"n": T[i][0], "id": T[i][1], "D": T[i][2].D, "nums": list(T[i][2].nums), "key": eng.target_key(i)}
        for i in unr_t])


def _user_moves(I, st):
    return {name: (I.moves[name], int(g)) for name, g in st["moves"].items() if name in I.moves}


def _gain(eng, T, before, after):
    g = {}
    for i, (n, o, _) in enumerate(T):
        k = eng.target_key(i)
        if k in after and k not in before:
            g.setdefault(n, []).append(o)
    return g


def eval_proposal(path, eng, T, reached, st, base, budget, log):
    rec = {"file": str(Path(path).relative_to(ROOT).as_posix()), "status": None}
    try:
        I, names = interpreter([path])
    except Exception as ex:
        rec.update(status="rejected: does not load", error=f"{type(ex).__name__}: {ex}"[:400])
        return rec, reached
    tops = [n for n in names if n in I.rules or n in I.moves]
    if len(tops) != 1:
        rec.update(status=f"rejected: must define exactly one rule or move (found {tops})")
        return rec, reached
    name = tops[0]
    rec["name"] = name
    src = Path(path).read_text(encoding="utf-8")
    t0 = time.time()
    if name in I.rules and I.rules[name].kind == "generative":
        rule = I.rules[name]
        rec["kind"] = "generative (new base pieces)"
        rec["reason"] = rule.meta.get("doc", "")
        with tempfile.TemporaryDirectory() as td:
            emit = Path(td) / "pts.json"
            try:
                cp = subprocess.run([PY, str(ROOT / "scripts/phase9/try_rule.py"), str(path), "--ns", "3-9",
                                     "--emit", str(emit)], capture_output=True, text=True, timeout=budget / 2,
                                    cwd=ROOT, env={**__import__("os").environ, "PYTHONIOENCODING": "utf-8"})
            except subprocess.TimeoutExpired:
                rec.update(status="dropped: generation exceeded half the budget")
                return rec, reached
            if cp.returncode != 0 or not emit.exists():
                rec.update(status="rejected: generation failed", error=cp.stderr[-400:])
                return rec, reached
            pts = [point_from_json(d) for d in load_json(emit)]
        pts = [p for p in pts if verify_vertex(p)["feasible"]]          # judge re-verifies; never trusts the tool
        keys = {group.canonical(p).key() for p in pts if p.n <= 9}
        new_keys = {k for k in keys if k not in base.get(int(k.split("|")[0]), ()) and k not in st["extra_base"]}
        rec.update(points=len(pts), orbits=len(keys), new_base_orbits=len(new_keys))
        if not new_keys:
            rec.update(status="dropped: no gain (no new base orbit)", seconds=round(time.time() - t0, 1))
            return rec, reached
        is_base = make_is_base(base, set(st["extra_base"]) | new_keys)
        with Forward(eng, [path], eng.workers, [k for k in eng.rep if k not in reached]) as fw:
            after, to = eng.run(is_base, _user_moves(I, st), I, deadline=t0 + budget, skip=reached, verbose=False,
                                forward=fw)
        g = _gain(eng, T, reached, after)
        rec.update(timed_out=to, nodes_gained=len(after) - len(reached), targets_gained={n: len(v) for n, v in g.items()},
                   targets_gained_ids=g, seconds=round(time.time() - t0, 1))
        if g:
            st["extra_base"] = sorted(set(st["extra_base"]) | new_keys)
            rec["status"] = "ACCEPTED"
            _append_accepted(src, rec)
            return rec, after
        rec["status"] = "dropped: no gain" + (" within budget" if to else "")
        return rec, reached
    if name in I.moves:
        mv = I.moves[name]
        rec["kind"] = "move"
        rec["reason"] = mv.meta.get("doc", mv.meta.get("source", ""))
        if len(mv.params) != 1 or not isinstance(mv.grow, int) or mv.grow < 1:
            rec.update(status="rejected: only unary moves with integer :grow >= 1 are supported by the engine")
            return rec, reached
        um = _user_moves(I, st)
        um[name] = (mv, mv.grow)
        with Forward(eng, [path], eng.workers, [k for k in eng.rep if k not in reached]) as fw:
            after, to = eng.run(make_is_base(base, set(st["extra_base"])), um, I, deadline=t0 + budget, skip=reached,
                                verbose=False, forward=fw)
        g = _gain(eng, T, reached, after)
        rec.update(timed_out=to, nodes_gained=len(after) - len(reached), targets_gained={n: len(v) for n, v in g.items()},
                   targets_gained_ids=g, seconds=round(time.time() - t0, 1))
        if g:
            st["moves"][name] = mv.grow
            rec["status"] = "ACCEPTED"
            _append_accepted(src, rec)
            return rec, after
        rec["status"] = "dropped: no gain" + (" within budget" if to else "")
        return rec, reached
    rule = I.rules[name]                                   # structural claim
    rec["kind"] = "structural claim"
    rec["reason"] = rule.meta.get("doc", "")
    holds = {}
    for n in range(3, 9):
        lo = rule.meta.get("domain", (3,))
        if n < lo[0] or (len(lo) > 1 and n > lo[1]):
            continue
        if time.time() - t0 > budget:
            rec["timed_out"] = True
            break
        try:
            holds[n] = bool(I.run_rule(rule, n))
        except Exception as ex:
            holds[n] = f"error: {type(ex).__name__}: {ex}"[:200]
    rec.update(holds=holds, seconds=round(time.time() - t0, 1))
    bad = [n for n, v in holds.items() if v is False]
    if bad:
        rec["status"] = f"broken by the judge at n = {bad[0]} (exhaustive data)"
    elif holds and all(v is True for v in holds.values()):
        rec["status"] = "ACCEPTED (claim; open to the breaker)"
        _append_accepted(src, rec)
    else:
        rec["status"] = "rejected: errors or no tested n"
    return rec, reached


def _append_accepted(src, rec):
    if DRY["on"]:
        return
    with open(ACCEPTED, "a", encoding="utf-8", newline="\n") as f:
        f.write(f"\n;; accepted in Phase 9 ({rec['file']}): {rec.get('reason', '')}\n{src.strip()}\n")


def eval_candidates(path, eng, T, reached, st, base, I):
    out = []
    for it in load_json(path) if isinstance(load_json(path), list) else [load_json(path)]:
        r = {"file": str(Path(path).relative_to(ROOT).as_posix()), "claim": it.get("kind"), "rule": it.get("rule"),
             "how": it.get("how", "")}
        try:
            x = point_from_json(it)
        except Exception as ex:
            r["status"] = f"rejected: bad point ({ex})"
            out.append(r)
            continue
        v = verify_vertex(x)
        r.update(n=x.n, D=x.D, vertex=v["vertex"], feasible=v["feasible"], tight=v["tight"])
        if not v["vertex"]:
            r["status"] = "rejected: not a vertex"
            out.append(r)
            continue
        r["point"] = {"n": x.n, "D": x.D, "nums": list(x.nums)}
        if x.n <= 9:
            r["key"] = group.canonical(x).key()
        if x.n <= 8:
            idx = {group.canonical(p).key(): i + 1 for i, p in enumerate(deza.load_ext(x.n))}
            r["deza_orbit"] = idx.get(r["key"])
            if r["deza_orbit"] is None:
                r["status"] = "REJECTED: claims a vertex not in Deza's list (investigate)"
                out.append(r)
                continue
        if it.get("kind") == "counterexample":
            rule = it.get("rule")
            dom = I.rules[rule].meta.get("domain", (3,)) if rule in I.rules else (3,)
            if rule not in I.rules or I.rules[rule].kind != "structural":
                r["status"] = "rejected: unknown structural rule"
            elif x.n < dom[0] or (len(dom) > 1 and x.n > dom[1]):
                r["status"] = f"rejected: n = {x.n} outside the rule's domain {list(dom)}"
            else:
                try:
                    fails = not eval_structural_on(I, rule, x)
                    r["status"] = "CONFIRMED counterexample" if fails else "rejected: rule holds on this point"
                except Exception as ex:
                    r["status"] = f"rejected: rule error {type(ex).__name__}: {ex}"[:300]
        else:                                                  # claimed unreachable vertex
            if x.n <= 9:
                k = r["key"]
                if k in reached:
                    r["status"] = "rejected: reachable by the current rule set"
                else:
                    known = any(eng.target_key(i) == k for i in range(len(T)))
                    if not known:
                        eng.add_targets([x], verbose=False)
                        T.append((x.n, f"breaker:{Path(path).name}", x))
                        with Forward(eng, [], eng.workers, [k for k in eng.rep if k not in reached]) as fw:
                            after, _ = eng.run(make_is_base(base, set(st["extra_base"])), _user_moves(I, st), I,
                                               skip=reached, verbose=False, forward=fw)
                        reached.update(after)
                    r["status"] = ("rejected: reachable by the current rule set" if k in reached
                                   else "CONFIRMED unreachable (exact engine)")
            else:
                r["status"] = "CONFIRMED vertex (n >= 10: reachability not evaluated in 9a)"
        out.append(r)
    return out


def cmd_round(args):
    DRY["on"] = bool(getattr(args, "dry_run", False))
    R = args.round_no
    rdir = ROOT / "phase9" / f"round_{R:02d}"
    t_start = time.time()
    T = targets()
    eng = Engine(CK / "engine", workers=args.workers)
    reached, st = load_state()
    base = load_base()
    before = summarize(eng, T, reached)
    props = sorted((rdir / "maker").glob("*.mpr")) if (rdir / "maker").exists() else []
    # cheapest first: probe cost = time to load + run try_rule on n = 3..6 (cheap sizes)
    probe = {}
    for p in props:
        t = time.time()
        try:
            subprocess.run([PY, str(ROOT / "scripts/phase9/try_rule.py"), str(p), "--ns", "3-6", "--probe", "5"],
                           capture_output=True, timeout=60, cwd=ROOT)
            probe[p] = time.time() - t
        except subprocess.TimeoutExpired:
            probe[p] = 999.0
    props.sort(key=lambda p: probe[p])
    results = []
    for p in props:
        if time.time() - t_start > args.round_cap:
            results.append({"file": str(p.relative_to(ROOT).as_posix()), "status": "deferred: round cap reached"})
            continue
        rec, reached = eval_proposal(p, eng, T, reached, st, base, args.budget, None)
        rec["probe_seconds"] = round(probe[p], 2)
        results.append(rec)
        print(f"[round {R}] {rec.get('name', p.name)}: {rec['status']}  gain {rec.get('targets_gained', {})}", flush=True)
    I, _ = interpreter([])
    cands = []
    for c in sorted((rdir / "breaker").glob("*.json")) if (rdir / "breaker").exists() else []:
        if time.time() - t_start > args.round_cap:
            cands.append({"file": str(c.relative_to(ROOT).as_posix()), "status": "deferred: round cap reached"})
            continue
        cands += eval_candidates(c, eng, T, reached, st, base, I)
    # keep the smallest confirmed counterexample per rule on disk
    cdir = OUT / "counterexamples"
    cdir.mkdir(parents=True, exist_ok=True)
    smallest = {}
    for c in cands:
        if c.get("status") == "CONFIRMED counterexample":
            if c["rule"] not in smallest or c["n"] < smallest[c["rule"]]["n"]:
                smallest[c["rule"]] = c
    for rule, c in smallest.items():
        atomic_write_json(cdir / f"{rule}_n{c['n']}_round{R:02d}.json", c)
    after = summarize(eng, T, reached)
    st["history"].append({"round": R, "before": before, "after": after})
    if not DRY["on"]:
        write_state(eng, T, reached, st)
    rep = {"round": R, "code_version": code_version(), "git": git_head(), "seconds": round(time.time() - t_start, 1),
           "budget_per_rule": args.budget, "round_cap": args.round_cap, "proposals": results, "candidates": cands,
           "smallest_counterexamples": {r: f"{c['n']}" for r, c in smallest.items()},
           "unreached_before": before, "unreached_after": after}
    tag = "_dryrun" if DRY["on"] else ""
    atomic_write_json(OUT / f"round_{R:02d}{tag}.json", rep)
    atomic_write_text(OUT / f"round_{R:02d}{tag}.md", render(rep))
    print(render(rep))


def render(rep):
    md = [f"# Phase 9 round {rep['round']}", "",
          f"Judge time {rep['seconds']} s; budget per rule {rep['budget_per_rule']} s; round cap {rep['round_cap']} s.", "",
          "## Proposals (rule maker)", "", "| file | name | kind | status | targets gained (n: count) | s |", "|---|---|---|---|---|---|"]
    for p in rep["proposals"]:
        md.append(f"| {p['file']} | {p.get('name', '')} | {p.get('kind', '')} | {p['status']} | "
                  f"{p.get('targets_gained', '')} | {p.get('seconds', '')} |")
    md += ["", "## Candidates (rule breaker)", "", "| file | claim | rule | n | D | vertex | status |", "|---|---|---|---|---|---|---|"]
    for c in rep["candidates"]:
        md.append(f"| {c['file']} | {c.get('claim')} | {c.get('rule')} | {c.get('n')} | {c.get('D')} | "
                  f"{c.get('vertex')} | {c['status']} |")
    md += ["", "## Unreached targets (fraction)", "", "| n | before | after |", "|---|---|---|"]
    for n in ("7", "8", "9") if isinstance(next(iter(rep["unreached_before"])), str) else (7, 8, 9):
        b, a = rep["unreached_before"][n], rep["unreached_after"][n]
        md.append(f"| {n} | {b['unreached']}/{b['targets']} ({100 * b['unreached_fraction']:.1f}%) | "
                  f"{a['unreached']}/{a['targets']} ({100 * a['unreached_fraction']:.1f}%) |")
    return "\n".join(md) + "\n"
