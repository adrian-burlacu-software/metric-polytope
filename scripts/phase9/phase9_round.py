_FW = {}


def _fw_init(files, invs):
    I, _ = interpreter(files)
    _FW["I"] = I
    _FW["inv"] = invs


def _fw_apply(args):
    """Outputs of the move on the whole orbit of x that are (up to symmetry) unreached nodes. Filter by the exact
    orbit invariant first; equality is then decided by the canonical form."""
    from metricpoly import core as _core
    from metricpoly.reach import orbit_invariant
    name, x = args
    I = _FW["I"]
    try:
        outs = I.apply_move(I.moves[name], [x], as_orbits=True)
    except Exception:
        return []
    seen, keys = set(), set()
    for o in outs:
        if o.n > 9 or (o.n, o.D, o.nums) in seen:
            continue
        seen.add((o.n, o.D, o.nums))
        if orbit_invariant(o) in _FW["inv"] and _core.is_feasible(o):
            keys.add(group.canonical(o).key())
    return sorted(keys)


class Forward:
    """Pool of interpreters (rule set + given files) applying user moves forward to node representatives."""

    def __init__(self, eng, files, workers, unreached_keys, deadline=None):
        self.eng, self.files, self.workers = eng, [str(f) for f in files], workers
        self.invs = set(eng.invariants(list(unreached_keys)).values())
        self.deadline = deadline            # hard: a runaway forward application is cut off at the deadline

    def __enter__(self):
        import multiprocessing as mp
        self.pool = mp.Pool(self.workers, initializer=_fw_init, initargs=(self.files, self.invs))
        return self

    def __exit__(self, *a):
        self.pool.terminate()

    def __call__(self, name, keys):
        import multiprocessing as mp
        job = self.pool.map_async(_fw_apply, [(name, self.eng.point(k)) for k in keys], chunksize=4)
        try:
            res = job.get(timeout=None if self.deadline is None else max(1.0, self.deadline - time.time()))
        except mp.TimeoutError:
            return {}                       # engine sees the deadline passed and reports a timeout
        return dict(zip(keys, res))


def load_state(d=None):
    d = d or CK
    reached = {k: tuple(v) for k, v in load_json(d / "reached.json").items()}
    st = load_json(d / "state.json") if (d / "state.json").exists() else {"extra_base": [], "moves": {}, "history": []}
    return reached, st


def write_state(eng, T, reached, st):
    atomic_write_json(CK / "reached.json", {k: list(v) for k, v in reached.items()})
    atomic_write_json(CK / "state.json", st)
    unr_t = [i for i in range(len(T)) if eng.target_key(i) not in reached]
    atomic_write_json(OUT / "unreached_nodes.json", {
        "note": "keys = canonical keys 'n|D|nums' of every unreached node (restrictions of targets); target_keys = "
                "unreached targets (whole orbits). Generated by the judge; read-only for agents.",
        "keys": sorted(k for k in eng.rep if k not in reached),
        "target_keys": sorted({eng.target_key(i) for i in unr_t})})
    atomic_write_json(OUT / "unreached_targets.json", [
        {"n": T[i][0], "id": T[i][1], "D": T[i][2].D, "nums": list(T[i][2].nums), "key": eng.target_key(i)}
        for i in unr_t])


def _user_moves(I, st):
    return {name: (I.moves[name], int(g)) for name, g in st["moves"].items() if name in I.moves}


def _gain(eng, T, before, after):
    g = {}
    for i, (n, o, _) in enumerate(T):
        if not isinstance(o, int):                     # breaker-added points do not count as coverage
            continue
        k = eng.target_key(i)
        if k in after and k not in before:
            g.setdefault(n, []).append(o)
    return g


def coverage(eng, T, before, g):
    """Breadth of a rule's gain (user criterion: a rule catching a handful at one denominator is a disguised list).
    Per n: targets gained, share of that n's unreached targets, gains per denominator, distinct denominators."""
    out = {}
    for n, ids in g.items():
        dens = {}
        unr = 0
        for i, (m, o, x) in enumerate(T):
            if m != n or not isinstance(o, int):
                continue
            if eng.target_key(i) not in before:
                unr += 1
            if o in ids:
                dens[x.D] = dens.get(x.D, 0) + 1
        out[str(n)] = {"gained": len(ids), "share_of_unreached": round(len(ids) / max(unr, 1), 4),
                  "by_denominator": dict(sorted(dens.items())), "distinct_denominators": len(dens)}
    tot = sum(v["gained"] for v in out.values())
    ns = len(out)
    nd = len({d for v in out.values() for d in v["by_denominator"]})
    out["verdict"] = ("NARROW (likely a disguised list)" if tot < 10 or (ns == 1 and nd <= 1)
                      else "broad" if ns >= 2 and nd >= 3 else "moderate")
    return out


def eval_proposal(path, eng, T, reached, st, base, budget, log, variant=False):
    rec = {"file": str(Path(path).relative_to(ROOT).as_posix()), "status": None,
           "track": "VARIANT non-vertex (separate numbers)" if variant else "main"}
    acc_path = VARIANT_FILE if variant else ACCEPTED
    try:
        I, names = interpreter([path])
    except Exception as ex:
        rec.update(status="rejected: does not load", error=f"{type(ex).__name__}: {ex}"[:400])
        return rec, reached
    tops = [n for n in names if n in I.rules or n in I.moves]
    if len(tops) != 1:
        rec.update(status=f"rejected: must define exactly one rule or move (found {tops})")
        return rec, reached
    name = tops[0]
    rec["name"] = name
    obj = I.rules.get(name) or I.moves.get(name)
    dom = obj.meta.get("domain", (3,))
    if len(dom) > 1:
        rec.update(status=f"rejected: must run at every n (domain has an upper bound: {list(dom)})")
        return rec, reached
    src = Path(path).read_text(encoding="utf-8")
    t0 = time.time()
    if name in I.rules and I.rules[name].kind == "generative":
        rule = I.rules[name]
        rec["kind"] = "generative (new base pieces)"
        rec["reason"] = rule.meta.get("doc", "")
        with tempfile.TemporaryDirectory() as td:
            emit = Path(td) / "pts.json"
            try:
                cp = subprocess.run([PY, str(ROOT / "scripts/phase9/try_rule.py"), str(path), "--ns", "3-9",
                                     "--emit", str(emit)], capture_output=True, text=True, timeout=GEN_BUDGET,
                                    cwd=ROOT, env={**__import__("os").environ, "PYTHONIOENCODING": "utf-8"})
            except subprocess.TimeoutExpired:
                rec.update(status=f"dropped: generation exceeded the {GEN_BUDGET:.0f} s generation allowance")
                return rec, reached
            if cp.returncode != 0 or not emit.exists():
                rec.update(status="rejected: generation failed", error=cp.stderr[-400:])
                return rec, reached
            pts = [point_from_json(d) for d in load_json(emit)]
        chk = [(p, verify_vertex(p)) for p in pts]                     # judge re-verifies; never trusts the tool
        rec["non_vertex_points_discarded"] = 0 if variant else sum(1 for _, v in chk if v["feasible"] and not v["vertex"])
        # main track: base pieces must be exact vertices of m_k; the non-vertex variant accepts feasible points
        pts = [p for p, v in chk if (v["feasible"] if variant else v["vertex"])]
        keys = {group.canonical(p).key() for p in pts if p.n <= 9}
        new_keys = {k for k in keys if k not in base.get(int(k.split("|")[0]), ()) and k not in st["extra_base"]}
        rec.update(points=len(pts), orbits=len(keys), new_base_orbits=len(new_keys))
        if not new_keys:
            rec.update(status="dropped: no gain (no new base orbit)", seconds=round(time.time() - t0, 1))
            return rec, reached
        is_base = make_is_base(base, set(st["extra_base"]) | new_keys)
        rec["generation_seconds"] = round(time.time() - t0, 1)
        t1 = time.time()                                            # propagation budget starts after generation
        with Forward(eng, [path], eng.workers, [k for k in eng.rep if k not in reached], deadline=t1 + budget) as fw:
            after, to = eng.run(is_base, _user_moves(I, st), I, deadline=t1 + budget, skip=reached, verbose=False,
                                forward=fw)
        g = _gain(eng, T, reached, after)
        rec.update(timed_out=to, nodes_gained=len(after) - len(reached), targets_gained={n: len(v) for n, v in g.items()},
                   targets_gained_ids=g, coverage=coverage(eng, T, reached, g), seconds=round(time.time() - t0, 1))
        if g:
            st["extra_base"] = sorted(set(st["extra_base"]) | new_keys)
            rec["status"] = "ACCEPTED"
            _append_accepted(src, rec, acc_path)
            return rec, after
        rec["status"] = "dropped: no gain" + (" within budget" if to else "")
        return rec, reached
    if name in I.moves:
        mv = I.moves[name]
        rec["kind"] = "move"
        rec["reason"] = mv.meta.get("doc", mv.meta.get("source", ""))
        if len(mv.params) != 1 or not isinstance(mv.grow, int) or mv.grow < 1:
            rec.update(status="rejected: only unary moves with integer :grow >= 1 are supported by the engine")
            return rec, reached
        if not variant:
            ok, why = restriction_preserving(I, mv)
            rec["restriction_preserving"] = ok
            if not ok:
                rec.update(status="rejected: main-track moves must keep their input as a restriction (" + why +
                                  "); resubmit with :variant \"nonvertex\" to put it on the variant track")
                return rec, reached
        um = _user_moves(I, st)
        um[name] = (mv, mv.grow)
        with Forward(eng, [path], eng.workers, [k for k in eng.rep if k not in reached], deadline=t0 + budget) as fw:
            after, to = eng.run(make_is_base(base, set(st["extra_base"])), um, I, deadline=t0 + budget, skip=reached,
                                verbose=False, forward=fw)
        g = _gain(eng, T, reached, after)
        rec.update(timed_out=to, nodes_gained=len(after) - len(reached), targets_gained={n: len(v) for n, v in g.items()},
                   targets_gained_ids=g, coverage=coverage(eng, T, reached, g), seconds=round(time.time() - t0, 1))
        if g:
            st["moves"][name] = mv.grow
            rec["status"] = "ACCEPTED"
            _append_accepted(src, rec, acc_path)
            return rec, after
        rec["status"] = "dropped: no gain" + (" within budget" if to else "")
        return rec, reached
    rule = I.rules[name]                                   # structural claim
    rec["kind"] = "structural claim"
    rec["reason"] = rule.meta.get("doc", "")
    holds = {}
    for n in range(3, 9):
        lo = rule.meta.get("domain", (3,))
        if n < lo[0] or (len(lo) > 1 and n > lo[1]):
            continue
        if time.time() - t0 > budget:
            rec["timed_out"] = True
            break
        try:
            holds[n] = bool(I.run_rule(rule, n))
        except Exception as ex:
            holds[n] = f"error: {type(ex).__name__}: {ex}"[:200]
    rec.update(holds=holds, seconds=round(time.time() - t0, 1))
    bad = [n for n, v in holds.items() if v is False]
    if bad:
        rec["status"] = f"broken by the judge at n = {bad[0]} (exhaustive data)"
    elif holds and all(v is True for v in holds.values()):
        rec["status"] = "ACCEPTED (claim; open to the breaker)"
        _append_accepted(src, rec, acc_path)
    else:
        rec["status"] = "rejected: errors or no tested n"
    return rec, reached


def _append_accepted(src, rec, path=None):
    if DRY["on"]:
        return
    with open(path or ACCEPTED, "a", encoding="utf-8", newline="\n") as f:
        f.write(f"\n;; accepted in Phase 9 ({rec['file']}): {rec.get('reason', '')}\n{src.strip()}\n")


def restriction_preserving(I, mv, samples=12, seed=20261122):
    """Probe: on random vertices of m_5 and m_6, every output must contain (up to symmetry) the input as a
    restriction. Needed so that per-target reachability stays complete (every intermediate is a restriction)."""
    import itertools as it
    import random
    from metricpoly.dsl.prims import p_vertices
    rng = random.Random(seed)
    sys.path.insert(0, str(ROOT / "scripts"))
    import detour_depth2 as d2
    from fractions import Fraction
    from metricpoly.core import Point as _P
    verts = list(p_vertices(5)) + list(p_vertices(6))
    # intermediate points of derivations are often NOT vertices: probe halved vertices and restrictions too
    halves = [_P.from_fractions(v.n, [f / 2 for f in v.fractions()]) for v in rng.sample(verts, samples)]
    restr = []
    for x in rng.sample(list(deza.load_ext(7)) + list(deza.load_ext(8)), samples):
        S = sorted(rng.sample(range(x.n), rng.choice([5, 6])))
        restr.append(d2.restrict(d2.matrix(x), x.D, S))
    pool = rng.sample(verts, samples) + halves + restr
    for y in pool:
        try:
            outs = I.apply_move(mv, [y])
        except Exception as ex:
            return False, f"error on probe: {type(ex).__name__}"
        ky = group.canonical(y).key()
        for o in outs:
            M = d2.matrix(o)
            if not any(group.canonical(d2.restrict(M, o.D, S)).key() == ky
                       for S in it.combinations(range(o.n), y.n)):
                return False, f"an output on a {y.n}-node probe does not contain the input"
    return True, "ok"


_LR = {}


def _large_init(moves=None):
    """moves: the accepted moves {name: grow} from the IN-MEMORY round state (state.json is only written at the end of
    a round, so reading it here missed moves accepted earlier in the same round; bug found in round 6)."""
    I, _ = interpreter([])
    if moves is None:
        moves = load_json(CK / "state.json")["moves"]
    _LR["I"] = I
    _LR["moves"] = [(n_, int(g)) for n_, g in moves.items() if n_ in I.moves]


def _large_apply(name, p):
    from metricpoly import core as _core
    I = _LR["I"]
    try:
        return [o for o in I.apply_move(I.moves[name], [p], as_orbits=True) if _core.is_feasible(o)]
    except Exception:
        return []


def _large_reach(x):
    """n <= BU_MAX: bottom-up search with the accepted moves (complete when all moves are restriction-preserving);
    larger n: top-down search with the built-in moves only (verdict noted as such)."""
    from metricpoly.reach_large import BU_MAX, reachable, reachable_bu
    t = time.time()
    if x.n <= BU_MAX:
        v, stats = reachable_bu(x, _LR["moves"], _large_apply, budget=LARGE_BUDGET)
        return v, stats, round(time.time() - t, 1)
    v, nodes = reachable(x, budget=LARGE_BUDGET)
    return v, {"nodes": nodes, "note": "top-down, built-in moves only"}, round(time.time() - t, 1)


def eval_candidates(path, eng, T, reached, st, base, I):
    out = []
    for it in load_json(path) if isinstance(load_json(path), list) else [load_json(path)]:
        r = {"file": str(Path(path).relative_to(ROOT).as_posix()), "claim": it.get("kind"), "rule": it.get("rule"),
             "how": it.get("how", "")}
        try:
            x = point_from_json(it)
        except Exception as ex:
            r["status"] = f"rejected: bad point ({ex})"
            out.append(r)
            continue
        v = verify_vertex(x)
        r.update(n=x.n, D=x.D, vertex=v["vertex"], feasible=v["feasible"], tight=v["tight"])
        if not v["vertex"]:
            r["status"] = "rejected: not a vertex"
            out.append(r)
            continue
        r["point"] = {"n": x.n, "D": x.D, "nums": list(x.nums)}
        if x.n <= 9:
            r["key"] = group.canonical(x).key()
        if x.n <= 8:
            idx = {group.canonical(p).key(): i + 1 for i, p in enumerate(deza.load_ext(x.n))}
            r["deza_orbit"] = idx.get(r["key"])
            if r["deza_orbit"] is None:
                r["status"] = "REJECTED: claims a vertex not in Deza's list (investigate)"
                out.append(r)
                continue
        if it.get("kind") == "counterexample":
            rule = it.get("rule")
            dom = I.rules[rule].meta.get("domain", (3,)) if rule in I.rules else (3,)
            if rule not in I.rules or I.rules[rule].kind != "structural":
                r["status"] = "rejected: unknown structural rule"
            elif x.n < dom[0] or (len(dom) > 1 and x.n > dom[1]):
                r["status"] = f"rejected: n = {x.n} outside the rule's domain {list(dom)}"
            else:
                try:
                    fails = not eval_structural_on(I, rule, x)
                    r["status"] = "CONFIRMED counterexample" if fails else "rejected: rule holds on this point"
                except Exception as ex:
                    r["status"] = f"rejected: rule error {type(ex).__name__}: {ex}"[:300]
        else:                                                  # claimed unreachable vertex
            if x.n <= 9:
                k = r["key"]
                if k in reached:
                    r["status"] = "rejected: reachable by the current rule set"
                else:
                    known = any(eng.target_key(i) == k for i in range(len(T)))
                    if not known:
                        eng.add_targets([x], verbose=False)
                        T.append((x.n, f"breaker:{Path(path).name}", x))
                        with Forward(eng, [], eng.workers, [k for k in eng.rep if k not in reached]) as fw:
                            after, _ = eng.run(make_is_base(base, set(st["extra_base"])), _user_moves(I, st), I,
                                               skip=reached, verbose=False, forward=fw)
                        reached.update(after)
                    r["status"] = ("rejected: reachable by the current rule set" if k in reached
                                   else "CONFIRMED unreachable (exact engine)")
            else:
                # n >= 10: no canonical forms; exact top-down search (metricpoly/reach_large.py, validated n <= 9)
                from metricpoly.dsl.ext.phase8_prims import p_den_bound_ok
                from metricpoly.canon_large import canonical_key as _ck
                r["denominator_bound_violated"] = not p_den_bound_ok(x.D, x.n)
                r["key"] = _ck(x)                               # bliss-based canonical form (validated n <= 9)
                reg_path = OUT / "large_orbits.json"
                reg = load_json(reg_path) if reg_path.exists() else {}
                if r["key"] in reg:
                    r["status"] = f"rejected: duplicate orbit (first seen {reg[r['key']]})"
                    out.append(r)
                    continue
                if not DRY["on"]:
                    reg[r["key"]] = f"{Path(path).parent.parent.name}, n = {x.n}, D = {x.D}"
                    atomic_write_json(reg_path, reg)
                r["_x"] = x                                     # searched in parallel below
        out.append(r)
    pend = [r for r in out if "_x" in r]
    if pend:
        import multiprocessing as mp
        with mp.Pool(min(len(pend), eng.workers), initializer=_large_init, initargs=(dict(st["moves"]),)) as pool:
            jobs = [pool.apply_async(_large_reach, (r["_x"],)) for r in pend]
            res = []
            t_hard = time.time() + LARGE_BUDGET * (1 + len(pend) / max(1, min(len(pend), eng.workers))) + 30
            for jb in jobs:                 # hard timeout: a runaway forward application cannot block the round
                try:
                    res.append(jb.get(timeout=max(1.0, t_hard - time.time())))
                except mp.TimeoutError:
                    res.append((None, {"hard_timeout": True}, None))
            pool.terminate()
        for r, (v, nodes, secs) in zip(pend, res):
            del r["_x"]
            r["search_nodes"], r["search_seconds"] = nodes, secs
            r["status"] = {True: "rejected: reachable by the current rule set",
                           False: "CONFIRMED unreachable (complete search)",
                           None: "CONFIRMED vertex; reachability UNDECIDED (budget or size limits)"}[v]
            if r["denominator_bound_violated"]:
                r["status"] += "; provably unreachable by the denominator lemma (Theorem 4)"
    return out


def cmd_round(args):
    DRY["on"] = bool(getattr(args, "dry_run", False))
    R = args.round_no
    rdir = ROOT / "phase9" / f"round_{R:02d}"
    t_start = time.time()
    T = targets()
    eng = Engine(CK / "engine", workers=args.workers)
    reached, st = load_state()
    base = load_base()
    before = summarize(eng, T, reached)
    props = sorted((rdir / "maker").glob("*.mpr")) if (rdir / "maker").exists() else []
    # cheapest first: probe cost = time to load + run try_rule on n = 3..6 (cheap sizes)
    probe = {}
    for p in props:
        t = time.time()
        try:
            subprocess.run([PY, str(ROOT / "scripts/phase9/try_rule.py"), str(p), "--ns", "3-6", "--probe", "5"],
                           capture_output=True, timeout=60, cwd=ROOT)
            probe[p] = time.time() - t
        except subprocess.TimeoutExpired:
            probe[p] = 999.0
    props.sort(key=lambda p: probe[p])
    results = []
    for p in props:
        if time.time() - t_start > args.round_cap:
            results.append({"file": str(p.relative_to(ROOT).as_posix()), "status": "deferred: round cap reached"})
            continue
        is_var = ':variant "nonvertex"' in p.read_text(encoding="utf-8")
        if is_var:
            vreached, vst = load_state(VDIR)
            rec, vreached = eval_proposal(p, eng, T, vreached, vst, base, args.budget, None, variant=True)
            if not DRY["on"]:
                atomic_write_json(VDIR / "reached.json", {k: list(v) for k, v in vreached.items()})
                atomic_write_json(VDIR / "state.json", vst)
                vlog = load_json(OUT / "variant_nonvertex.json")
                vlog["rules"].append({"round": R, "rule": rec.get("name"), "status": rec["status"],
                                      "targets_gained": rec.get("targets_gained"),
                                      "unreached_after": summarize(eng, T, vreached)})
                atomic_write_json(OUT / "variant_nonvertex.json", vlog)
        else:
            rec, reached = eval_proposal(p, eng, T, reached, st, base, args.budget, None)
        rec["probe_seconds"] = round(probe[p], 2)
        results.append(rec)
        print(f"[round {R}] {rec.get('name', p.name)}: {rec['status']}  gain {rec.get('targets_gained', {})}", flush=True)
    # ---- one retry at RETRY_BUDGET for main-track rules dropped by the budget while still gaining sub-orbits
    # (this round's, plus the previous round's that were never retried); cheapest first, while the round cap allows
    def _retry_ok(rec):
        return (rec.get("track", "main") == "main" and rec.get("timed_out") and (rec.get("nodes_gained") or 0) > 0
                and str(rec.get("status", "")).startswith("dropped") and not rec.get("retry"))
    retry = [(ROOT / rec["file"], rec.get("probe_seconds", 999.0), R) for rec in results if _retry_ok(rec)]
    prev = OUT / f"round_{R - 1:02d}.json"
    if prev.exists():
        prev_recs = load_json(prev).get("proposals", [])
        # a rule already retried in that round (accepted, dropped, or failed: anything but deferred) is not retried again
        done_files = {r["file"] for r in prev_recs if r.get("retry") and not str(r.get("status", "")).startswith("retry deferred")}
        for rec in prev_recs:
            if _retry_ok(rec) and rec["file"] not in done_files and (ROOT / rec["file"]).exists():
                retry.append((ROOT / rec["file"], rec.get("probe_seconds", 999.0), R - 1))
    for path, ps, origin in sorted(retry, key=lambda t: t[1]):
        if time.time() - t_start + RETRY_BUDGET > args.round_cap:
            results.append({"file": str(path.relative_to(ROOT).as_posix()), "retry": True,
                            "status": "retry deferred: not enough time left in the round cap"})
            continue
        rec, reached = eval_proposal(path, eng, T, reached, st, base, RETRY_BUDGET, None)
        rec.update(retry=True, retry_of_round=origin, probe_seconds=ps)
        results.append(rec)
        print(f"[round {R}] RETRY {rec.get('name', path.name)} (from round {origin}, {RETRY_BUDGET:.0f} s): "
              f"{rec['status']}  gain {rec.get('targets_gained', {})}", flush=True)
    I, _ = interpreter([])
    cands = []
    for c in sorted((rdir / "breaker").glob("candidates*.json")) if (rdir / "breaker").exists() else []:
        if time.time() - t_start > args.round_cap:
            cands.append({"file": str(c.relative_to(ROOT).as_posix()), "status": "deferred: round cap reached"})
            continue
        cands += eval_candidates(c, eng, T, reached, st, base, I)
    # keep the smallest confirmed counterexample per rule on disk
    cdir = OUT / "counterexamples"
    cdir.mkdir(parents=True, exist_ok=True)
    smallest = {}
    for c in cands:
        if c.get("status") == "CONFIRMED counterexample":
            if c["rule"] not in smallest or c["n"] < smallest[c["rule"]]["n"]:
                smallest[c["rule"]] = c
    for rule, c in smallest.items():
        if not DRY["on"]:
            atomic_write_json(cdir / f"{rule}_n{c['n']}_round{R:02d}.json", c)
    after = summarize(eng, T, reached)
    st["history"].append({"round": R, "before": before, "after": after})
    if not DRY["on"]:
        write_state(eng, T, reached, st)
    rep = {"round": R, "code_version": code_version(), "git": git_head(), "seconds": round(time.time() - t_start, 1),
           "budget_per_rule": args.budget, "round_cap": args.round_cap, "proposals": results, "candidates": cands,
           "smallest_counterexamples": {r: f"{c['n']}" for r, c in smallest.items()},
           "unreached_before": before, "unreached_after": after}
    tag = "_dryrun" if DRY["on"] else ""
    atomic_write_json(OUT / f"round_{R:02d}{tag}.json", rep)
    atomic_write_text(OUT / f"round_{R:02d}{tag}.md", render(rep))
    print(render(rep))


def render(rep):
    md = [f"# Phase 9 round {rep['round']}", "",
          "Main-track numbers only. Non-vertex variant proposals are marked VARIANT and are tracked in "
          "results/phase9/variant_nonvertex.json.", "",
          f"Judge time {rep['seconds']} s; budget per rule {rep['budget_per_rule']} s (one retry at 900 s for rules still gaining); round cap {rep['round_cap']} s.", "",
          "## Proposals (rule maker)", "", "| file | name | kind | status | targets gained (n: count) | s |", "|---|---|---|---|---|---|"]
    for p in rep["proposals"]:
        md.append(f"| {p['file']} | {p.get('name', '')} | {p.get('kind', '')}{' (VARIANT)' if p.get('track', '').startswith('VAR') else ''} | {p['status']} | "
                  f"{p.get('targets_gained', '')} | {p.get('seconds', '')} |")
    cov = [p for p in rep["proposals"] if p.get("coverage")]
    if cov:
        md += ["", "## Coverage of rules with gains (per size and denominator)", "",
               "| rule | status | n | gained | share of unreached | denominators (D: count) | verdict |",
               "|---|---|---|---|---|---|---|"]
        for p in cov:
            c = p["coverage"]
            for n in sorted(k for k in c if k != "verdict"):
                v = c[n]
                md.append(f"| {p.get('name')} | {p['status'][:20]} | {n} | {v['gained']} | "
                          f"{100 * v['share_of_unreached']:.1f}% | {v['by_denominator']} | {c['verdict']} |")
    md += ["", "## Candidates (rule breaker)", "", "| file | claim | rule | n | D | vertex | status |", "|---|---|---|---|---|---|---|"]
    for c in rep["candidates"]:
        md.append(f"| {c['file']} | {c.get('claim')} | {c.get('rule')} | {c.get('n')} | {c.get('D')} | "
                  f"{c.get('vertex')} | {c['status']} |")
    md += ["", "## Unreached targets (fraction)", "", "| n | before | after |", "|---|---|---|"]
    for n in ("7", "8", "9") if isinstance(next(iter(rep["unreached_before"])), str) else (7, 8, 9):
        b, a = rep["unreached_before"][n], rep["unreached_after"][n]
        md.append(f"| {n} | {b['unreached']}/{b['targets']} ({100 * b['unreached_fraction']:.1f}%) | "
                  f"{a['unreached']}/{a['targets']} ({100 * a['unreached_fraction']:.1f}%) |")
    return "\n".join(md) + "\n"
