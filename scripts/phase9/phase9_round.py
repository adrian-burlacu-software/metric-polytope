"""Phase 9 round evaluation (called by judge.py). Exact checks only; agents' claims count only if confirmed here.

Order inside a round: proposals are evaluated cheapest first (measured probe time), each against the CURRENT state
(targets already reached are crossed off and never retried). Each proposal gets --budget seconds of engine time; if it
reaches no new target within budget it is dropped as "no gain". The whole round stops after --round-cap seconds.
"""
from __future__ import annotations

import json
