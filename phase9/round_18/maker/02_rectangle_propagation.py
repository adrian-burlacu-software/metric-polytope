"""Sufficient, any weights (proved).  Step 1: classes of node pairs under 'opposite sides of a geodesic rectangle'
(equal length in every solution, see 01).  Step 2: fix the length of one class; whenever a geodesic triple
long = short1 + short2 has exactly one class of unknown length, that length follows.  If every class becomes
known, d is a ray.

Why it is sufficient (holds for every k and every weight alphabet): the tight triangle equalities are exactly
x_ab = x_am + x_mb for geodesic triples (m between a and b).  Every step derives a linear consequence of these
equalities, and at the end every pair length is a fixed rational multiple of one of them, so the solution space
of the tight system is one-dimensional, i.e. its rank is C(k,2) - 1.
"""
NAME = "rectangle-propagation"
KIND = "sufficient"
STATEMENT = (
    'If, after identifying opposite sides of every geodesic rectangle, the length of one class of '
    'node pairs determines all others by repeatedly applying geodesic triples d_ab = d_am + d_mb in '
    'which only one class is still undetermined, then the graph is a ray.'
)

INF = 10 ** 9


def _dist(k, edges):
    d = [[INF] * k for _ in range(k)]
    for i in range(k):
        d[i][i] = 0
    for a, b, w in edges:
        if w < d[a][b]:
            d[a][b] = d[b][a] = w
    for m in range(k):
        dm = d[m]
        for i in range(k):
            dim, di = d[i][m], d[i]
            for j in range(k):
                if dim + dm[j] < di[j]:
                    di[j] = dim + dm[j]
    return d


def _pr(a, b):
    return (a, b) if a < b else (b, a)


def _pairs(k):
    return [(a, b) for a in range(k) for b in range(a + 1, k)]


def _connected(k, d):
    return all(d[a][b] < INF for a, b in _pairs(k))


def _tight(k, d):
    """Geodesic triples (a, b, m): m lies strictly between a and b."""
    return [(a, b, m) for a in range(k) for b in range(a + 1, k) for m in range(k)
            if m != a and m != b and d[a][b] == d[a][m] + d[m][b]]


class _UF:
    def __init__(self, items=()):
        self.p = {x: x for x in items}

    def f(self, x):
        self.p.setdefault(x, x)
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def u(self, x, y):
        self.p[self.f(x)] = self.f(y)


def _rectangle_classes(k, d):
    """Classes of node pairs generated by: opposite sides of a geodesic rectangle a, a2, b, b2
    (a2 and b2 both between a and b; a and b both between a2 and b2) are equivalent."""
    uf = _UF(_pairs(k))
    for a in range(k):
        for b in range(a + 1, k):
            mids = [m for m in range(k) if m != a and m != b and d[a][b] == d[a][m] + d[m][b]]
            for a2 in mids:
                for b2 in mids:
                    if a2 < b2 and d[a2][b2] == d[a2][a] + d[a][b2] and d[a2][b2] == d[a2][b] + d[b][b2]:
                        uf.u(_pr(a, a2), _pr(b, b2))
                        uf.u(_pr(a, b2), _pr(b, a2))
    return uf


def _class_eqs(T, uf):
    """Distinct class relations S = P + Q, one per geodesic triple."""
    out = set()
    for a, b, m in T:
        p, q = sorted((uf.f(_pr(a, m)), uf.f(_pr(m, b))))
        out.add((uf.f(_pr(a, b)), p, q))
    return sorted(out)


def _propagates(k, T, uf):
    """True if, from the length of one class, every class length follows by repeatedly using a geodesic
    triple (long = short1 + short2) in which exactly one class is still unknown."""
    from fractions import Fraction
    classes = {uf.f(p) for p in _pairs(k)}
    eqs = []
    for S, P, Q in _class_eqs(T, uf):
        co = {}
        for r, c in ((S, 1), (P, -1), (Q, -1)):
            co[r] = co.get(r, 0) + c
        co = {r: c for r, c in co.items() if c}
        if co:
            eqs.append(co)
    for seed in classes:
        val = {seed: Fraction(1)}
        changed = True
        while changed:
            changed = False
            for co in eqs:
                unk = [r for r in co if r not in val]
                if len(unk) == 1:
                    val[unk[0]] = -sum(c * val[r] for r, c in co.items() if r != unk[0]) / co[unk[0]]
                    changed = True
        if len(val) == len(classes):
            return True
    return False


def claim(k, edges):
    d = _dist(k, edges)
    if not _connected(k, d):
        return False
    return _propagates(k, _tight(k, d), _rectangle_classes(k, d))
