"""Sufficient, unweighted (proved).  Geodesic rectangle: four nodes a, a2, b, b2 with a2 and b2 both between a and b,
and a and b both between a2 and b2.  Then x_aa2 + x_a2b = x_ab2 + x_b2b and x_a2b + x_bb2 = x_a2a + x_ab2;
subtracting gives x_aa2 = x_bb2 and x_a2b = x_ab2: opposite sides of a geodesic rectangle have equal length in
every solution of the tight system.  In an unweighted graph the induced 4-cycles are the smallest rectangles;
isometric even cycles give larger ones.  If all edges fall in one class, all edges have one common length t and
every pair has length t * d (sum along a geodesic), so d is a ray.  Examples: K_{2,3}, K_{3,3}.

Why it is sufficient (holds for every k and every weight alphabet): the tight triangle equalities are exactly
x_ab = x_am + x_mb for geodesic triples (m between a and b).  Every step derives a linear consequence of these
equalities, and at the end every pair length is a fixed rational multiple of one of them, so the solution space
of the tight system is one-dimensional, i.e. its rank is C(k,2) - 1.
"""
NAME = "unit-rectangle-class"
KIND = "sufficient"
STATEMENT = (
    "If all weights are 1 and the equivalence on node pairs generated by 'opposite sides of a "
    'geodesic rectangle (a, a2, b, b2 with a2, b2 both between a and b and a, b both between a2 and '
    "b2)' puts all edges in one class, then the graph is a ray."
)

INF = 10 ** 9


def _dist(k, edges):
    d = [[INF] * k for _ in range(k)]
    for i in range(k):
        d[i][i] = 0
    for a, b, w in edges:
        if w < d[a][b]:
            d[a][b] = d[b][a] = w
    for m in range(k):
        dm = d[m]
        for i in range(k):
            dim, di = d[i][m], d[i]
            for j in range(k):
                if dim + dm[j] < di[j]:
                    di[j] = dim + dm[j]
    return d


def _pr(a, b):
    return (a, b) if a < b else (b, a)


def _pairs(k):
    return [(a, b) for a in range(k) for b in range(a + 1, k)]


def _connected(k, d):
    return all(d[a][b] < INF for a, b in _pairs(k))


def _tight(k, d):
    """Geodesic triples (a, b, m): m lies strictly between a and b."""
    return [(a, b, m) for a in range(k) for b in range(a + 1, k) for m in range(k)
            if m != a and m != b and d[a][b] == d[a][m] + d[m][b]]


class _UF:
    def __init__(self, items=()):
        self.p = {x: x for x in items}

    def f(self, x):
        self.p.setdefault(x, x)
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def u(self, x, y):
        self.p[self.f(x)] = self.f(y)


def _rectangle_classes(k, d):
    """Classes of node pairs generated by: opposite sides of a geodesic rectangle a, a2, b, b2
    (a2 and b2 both between a and b; a and b both between a2 and b2) are equivalent."""
    uf = _UF(_pairs(k))
    for a in range(k):
        for b in range(a + 1, k):
            mids = [m for m in range(k) if m != a and m != b and d[a][b] == d[a][m] + d[m][b]]
            for a2 in mids:
                for b2 in mids:
                    if a2 < b2 and d[a2][b2] == d[a2][a] + d[a][b2] and d[a2][b2] == d[a2][b] + d[b][b2]:
                        uf.u(_pr(a, a2), _pr(b, b2))
                        uf.u(_pr(a, b2), _pr(b, a2))
    return uf


def claim(k, edges):
    if any(w != 1 for _, _, w in edges):
        return False
    d = _dist(k, edges)
    if not _connected(k, d):
        return False
    uf = _rectangle_classes(k, d)
    return len({uf.f(_pr(a, b)) for a, b, w in edges}) == 1
